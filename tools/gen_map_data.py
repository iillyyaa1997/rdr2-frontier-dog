#!/usr/bin/env python3
"""Generate data/FrontierDog/Herbs.dat and Telegraph.dat from jeanropke/RDOMap (Unlicense) data files.

Map coordinates (lat, lng) -> game (x, y): x = (lng - 111.29) / 0.01552, y = (lat + 63.6) / 0.01552 (checked against the
Valentine stable: map -> (-369.5, 787.9), bcc-stables config (-367.9, 784.3)). Heights are found in game (ground probe).
usage: tools/gen_map_data.py .cache/rdomap_plants.json .cache/rdomap_shops.json <rev>
"""
import json, sys

def conv(p):
    return (p["y"] - 111.29) / 0.01552, (p["x"] + 63.6) / 0.01552

plants, shops, rev = sys.argv[1], sys.argv[2], sys.argv[3]
out = ["# Herb spots for «Найди травы» and the Herbalist trait (plan D131): generated by tools/gen_map_data.py from",
       f"# github.com/jeanropke/RDOMap data/plants.json @ {rev} (Unlicense). Online-map spots: single-player match unverified.",
       "# herb.<kind>=x,y;x,y;... (game coordinates, no height)"]
kinds = []
for p in json.load(open(plants)):
    kinds.append(p["key"])
    pts = ";".join("%.0f,%.0f" % conv(l) for l in p["locations"])
    out.append(f"herb.{p['key']}={pts}")
out.insert(3, "herbs=" + ",".join(kinds))
open("data/FrontierDog/Herbs.dat", "w").write("\n".join(out) + "\n")
tel = ["# Post offices (telegraph) for delivery orders (D116): from jeanropke/RDOMap data/shops.json @ " + rev + " (Unlicense)"]
names = []
for s in json.load(open(shops)):
    if s["key"] != "post_office":
        continue
    for l in s["locations"]:
        k = l["text"].replace("shop_", "").replace("_post_office", "")
        names.append(k)
        x, y = conv(l)
        tel.append(f"telegraph.{k}=%.1f,%.1f" % (x, y))
tel.insert(1, "telegraphs=" + ",".join(names))
open("data/FrontierDog/Telegraph.dat", "w").write("\n".join(tel) + "\n")
print(len(kinds), "herb kinds,", len(names), "post offices")
